def _render_icon_png(path: Path, size: int) -> None:
    """Render a crisp anti-aliased Minty scoop icon via 4x supersampling in Pillow."""
    from PIL import Image, ImageDraw

    scale = 4
    s = size * scale
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    # Dark rounded-square background (maskable-friendly safe zone)
    draw.rounded_rectangle(
        [(0, 0), (s - 1, s - 1)], radius=int(s * 0.22), fill="#18181B"
    )

    def circle(cx: float, cy: float, r: float, fill: str) -> None:
        x0, y0 = (cx - r) * s, (cy - r) * s
        x1, y1 = (cx + r) * s, (cy + r) * s
        draw.ellipse([(x0, y0), (x1, y1)], fill=fill)

    # Mint-choc-chip scoop + scalloped baseuffs
    circle(0.50, 0.365, 0.18, "#86EFAC")
    circle(0.41, 0.47, 0.10, "#86EFAC")
    circle(0.59, 0.47, 0.10, "#86EFAC")
    circle(0.50, 0.48, 0.105, "#A7F3D0")

    # Chocolate chips
    circle(0.46, 0.325, 0.019, "#18181B")
    circle(0.55, 0.375, 0.017, "#18181B")
    circle(0.48, 0.418, 0.015, "#18181B")

    # Porcelain cup body
    draw.polygon(
        [
            (0.305 * s, 0.525 * s),
            (0.695 * s, 0.525 * s),
            (0.625 * s, 0.795 * s),
            (0.375 * s, 0.795 * s),
        ],
        fill="#F4F4F5",
    )
    draw.rounded_rectangle(
        [(0.375 * s, 0.755 * s), (0.625 * s, 0.825 * s)],
        radius=int(0.035 * s),
        fill="#F4F4F5",
    )
    # Cup rim
    draw.rounded_rectangle(
        [(0.28 * s, 0.50 * s), (0.72 * s, 0.555 * s)],
        radius=int(0.028 * s),
        fill="#FFFFFF",
    )

    out = img.resize((size, size), Image.Resampling.LANCZOS)
    out.save(path, format="PNG", optimize=True)


def write_pwa_assets(dist_dir: Path, html_content: str) -> None:
    """Write icons, manifest.webmanifest, and network-first sw.js into dist/."""
    (dist_dir / "icon.svg").write_text(ICON_SVG, encoding="utf-8")
    _render_icon_png(dist_dir / "icon-192.png", 192)
    _render_icon_png(dist_dir / "icon-512.png", 512)
    _render_icon_png(dist_dir / "apple-touch-icon.png", 180)

    manifest = {
        "name": "Minty — Ice Cream Recipes",
        "short_name": "Minty",
        "description": "Canonical 1.2L ice cream & sorbet recipes and batch wizard.",
        "start_url": "./",
        "scope": "./",
        "display": "standalone",
        "background_color": "#121214",
        "theme_color": "#121214",
        "icons": [
            {
                "src": "icon.svg",
                "sizes": "any",
                "type": "image/svg+xml",
                "purpose": "any",
            },
            {
                "src": "icon-192.png",
                "sizes": "192x192",
                "type": "image/png",
                "purpose": "any maskable",
            },
            {
                "src": "icon-512.png",
                "sizes": "512x512",
                "type": "image/png",
                "purpose": "any maskable",
            },
        ],
    }
    (dist_dir / "manifest.webmanifest").write_text(
        json.dumps(manifest, indent=2) + "\n",
        encoding="utf-8",
    )

    version_hash = hashlib.sha256(html_content.encode("utf-8")).hexdigest()[
        :10
    ]
    sw_js = f"""// Auto-generated by minty — network-first with offline cache fallback
const CACHE_NAME = 'minty-{version_hash}';
const PRECACHE_URLS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icon.svg',
  './icon-192.png',
  './icon-512.png',
  './apple-touch-icon.png',
  './ice_cream.pdf',
];

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  );
  self.skipWaiting();
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key.startsWith('minty-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
}});

self.addEventListener('fetch', (event) => {{
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) {{
    return;
  }}
  event.respondWith(
    fetch(req)
      .then((res) => {{
        if (res && res.ok) {{
          const copy = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
        }}
        return res;
      }})
      .catch(() =>
        caches.match(req).then((cached) => cached || caches.match('./index.html'))
      )
  );
}});
"""
    (dist_dir / "sw.js").write_text(sw_js, encoding="utf-8")
